CREATE TABLE IF NOT EXISTS orders(id TEXT PRIMARY KEY,token TEXT NOT NULL,data TEXT NOT NULL,total BIGINT NOT NULL,status TEXT NOT NULL,preference TEXT,payment TEXT,created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS inventory(id TEXT PRIMARY KEY,available INTEGER NOT NULL CHECK(available>=0));
CREATE TABLE IF NOT EXISTS catalog_settings(id INTEGER PRIMARY KEY CHECK(id=1),demo INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS products(id TEXT PRIMARY KEY,data TEXT NOT NULL,published INTEGER NOT NULL DEFAULT 0,search TEXT NOT NULL DEFAULT '',position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE TABLE IF NOT EXISTS catalog_imports(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,source TEXT NOT NULL,count INTEGER NOT NULL,created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS order_requests(key TEXT PRIMARY KEY,fingerprint TEXT NOT NULL,order_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS catalog_revision(id INTEGER PRIMARY KEY,version BIGINT NOT NULL);
INSERT INTO catalog_revision VALUES(1,0) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY,email TEXT UNIQUE NOT NULL,name TEXT NOT NULL,password TEXT NOT NULL,address TEXT NOT NULL DEFAULT '{}',created TEXT NOT NULL,verified INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,user_id TEXT NOT NULL,expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS order_users(order_id TEXT PRIMARY KEY,user_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS account_tokens(token TEXT PRIMARY KEY,user_id TEXT NOT NULL,purpose TEXT NOT NULL,expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS rate_limits(key TEXT PRIMARY KEY,count INTEGER NOT NULL,expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS checkout_attempts(key TEXT PRIMARY KEY,fingerprint TEXT NOT NULL,order_id TEXT UNIQUE NOT NULL,user_id TEXT NOT NULL,url TEXT,expires BIGINT NOT NULL,released INTEGER NOT NULL DEFAULT 0,settled INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS order_users_user ON order_users(user_id);
CREATE INDEX IF NOT EXISTS account_tokens_expiry ON account_tokens(expires);
CREATE INDEX IF NOT EXISTS rate_expiry ON rate_limits(expires);
CREATE UNIQUE INDEX IF NOT EXISTS checkout_active_user ON checkout_attempts(user_id) WHERE released=0 AND settled=0;
CREATE INDEX IF NOT EXISTS products_category ON products(published,((data::jsonb)->>'category'));
CREATE INDEX IF NOT EXISTS products_price ON products(published,(((data::jsonb)->>'price')::bigint));
CREATE OR REPLACE FUNCTION oscal_catalog_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE catalog_revision SET version=version+1 WHERE id=1;
  RETURN NULL;
END;
$$;
DO $$
DECLARE target TEXT;
BEGIN
  FOREACH target IN ARRAY ARRAY['products','inventory','catalog_settings'] LOOP
    IF NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgname='oscal_revision_' || target AND tgrelid=target::regclass) THEN
      EXECUTE format('CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH STATEMENT EXECUTE FUNCTION oscal_catalog_changed()', 'oscal_revision_' || target, target);
    END IF;
  END LOOP;
END $$;
